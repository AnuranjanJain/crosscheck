def F(
    fact_id,
    doc,
    page,
    quote,
    subject,
    predicate,
    value_text,
    value_number,
    unit,
    period,
    scope,
    estimate_status,
    rationale,
):
    return {
        "id": fact_id,
        "document_filename": doc,
        "pdf_page_index": page,
        "evidence_quote": quote,
        "subject": subject,
        "predicate": predicate,
        "value_text": value_text,
        "value_number": value_number,
        "unit": unit,
        "period": period,
        "scope": scope,
        "estimate_status": estimate_status,
        "rationale": rationale,
    }


def R(rel_id, left, right, label, rationale):
    return {
        "id": rel_id,
        "left_fact_id": left,
        "right_fact_id": right,
        "expected_label": label,
        "rationale": rationale,
    }


def package(split, dataset, facts, relationships, notes):
    if len(facts) < 20:
        raise SystemExit(f"{dataset}/{split}: need >=20 facts, got {len(facts)}")
    if len(relationships) < 8:
        raise SystemExit(f"{dataset}/{split}: need >=8 relationships, got {len(relationships)}")
    fact_ids = {fact["id"] for fact in facts}
    for rel in relationships:
        if rel["left_fact_id"] not in fact_ids or rel["right_fact_id"] not in fact_ids:
            raise SystemExit(f"{dataset}/{split}: relationship {rel['id']} references unknown fact")
    return {
        "version": "v1",
        "split": split,
        "dataset": dataset,
        "created_on": "2026-09-08",
        "notes": notes,
        "facts": facts,
        "relationships": relationships,
    }


